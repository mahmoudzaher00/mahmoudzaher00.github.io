const dialog = document.querySelector('#project-dialog');
let projectOpener = null;
for (const button of document.querySelectorAll('[data-project]')) {
  button.addEventListener('click', () => {
    const project = projects[button.dataset.project];
    if (!project) return;
    projectOpener = button;
    document.querySelector('#dialog-category').textContent = project.category;
    document.querySelector('#dialog-title').textContent = project.title;
    document.querySelector('#dialog-description').textContent = project.description;
    document.querySelector('#dialog-points').replaceChildren(...project.points.map(text => {
      const li = document.createElement('li');
      li.textContent = text;
      return li;
    }));
    document.querySelector('#dialog-availability').textContent = project.availability || '';
    document.querySelector('#dialog-links').replaceChildren(...(project.links || []).map(link => {
      const a = document.createElement('a');
      a.href = link.url;
      a.textContent = link.label + ' ↗';
      a.target = '_blank';
      a.rel = 'noopener noreferrer';
      return a;
    }));
    const logo = document.querySelector('#dialog-logo');
    logo.hidden = false;
    logo.src = project.logo;
    logo.alt = project.title + ' app logo';
    dialog.showModal();
  });
}
dialog.addEventListener('close', () => projectOpener?.focus());
document.querySelector('.close').addEventListener('click', () => dialog.close());
document.querySelector('#discuss-project').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => {
  if (event.target !== dialog) return;
  const rect = dialog.getBoundingClientRect();
  if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) dialog.close();
});
for (const button of document.querySelectorAll('[data-filter]')) {
  button.addEventListener('click', () => {
    for (const filter of document.querySelectorAll('[data-filter]')) {
      const active = filter === button;
      filter.classList.toggle('active', active);
      filter.setAttribute('aria-pressed', String(active));
    }
    if (button.dataset.filter !== 'all') document.querySelector('#more-apps').open = true;
    for (const card of document.querySelectorAll('[data-category]')) {
      card.hidden = button.dataset.filter !== 'all' && card.dataset.category !== button.dataset.filter;
    }
  });
}
